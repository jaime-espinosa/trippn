export function placeById(id: string | null): Place | undefined {
  if (!id) return undefined;
  return PLACES.find((p) => p.id === id);
}

export function driveHours(drive: string): number {
  const n = Number.parseFloat(drive);
  return Number.isFinite(n) ? n : 99;
}

export function visiblePlaces(
  query: string,
  category: "all" | Category,
  sort: "region" | "drive",
): Place[] {
  const q = query.trim().toLowerCase();
  const list = PLACES.filter((p) => {
    if (category !== "all" && p.category !== category) return false;
    if (!q) return true;
    return (
      p.name.toLowerCase().includes(q) ||
      p.aka.toLowerCase().includes(q) ||
      p.corridor.toLowerCase().includes(q) ||
      p.region.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.note.toLowerCase().includes(q)
    );
  });
  if (sort === "drive") {
    return [...list].sort(
      (a, b) => driveHours(a.drive) - driveHours(b.drive) || a.name.localeCompare(b.name),
    );
  }
  return [...list].sort((a, b) => {
    const d = REGIONS.indexOf(a.region) - REGIONS.indexOf(b.region);
    return d !== 0 ? d : driveHours(a.drive) - driveHours(b.drive);
  });
}

export function categoryKey(category: Category): "view" | "camp" | "town" | "park" {
  if (category === "Viewpoints & Landmarks") return "view";
  if (category === "Campgrounds & Recreation") return "camp";
  if (category === "Towns & Cities") return "town";
  return "park";
}

